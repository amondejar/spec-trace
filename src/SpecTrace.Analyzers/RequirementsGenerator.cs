using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Security;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;
using SpecTrace.Specs;

namespace SpecTrace.Analyzers
{
    /// <summary>
    /// Genera, a partir de los ficheros *.spec.md:
    /// 1. Un catálogo tipado <c>Requirements</c> / <c>AcceptanceCriteria</c> para referenciar IDs sin cadenas mágicas.
    /// 2. Atributos de ensamblado <c>[assembly: SpecTraceImplemented("...")]</c> con lo que implementa el proyecto,
    ///    para que los proyectos de test sepan qué tienen que verificar.
    /// </summary>
    [Generator(LanguageNames.CSharp)]
    public sealed class RequirementsGenerator : IIncrementalGenerator
    {
        private const string Version = "0.4.0";

        public void Initialize(IncrementalGeneratorInitializationContext context)
        {
            var catalog = context.AdditionalTextsProvider
                .Where(SpecFiles.IsSpec)
                .Select((text, ct) => SpecFiles.Parse(text, ct))
                .Collect()
                .Select((docs, _) => SpecCatalog.Build(docs));

            var options = context.AnalyzerConfigOptionsProvider
                .Select((provider, _) => SpecTraceOptions.From(provider.GlobalOptions));

            context.RegisterSourceOutput(catalog.Combine(options), (spc, pair) =>
            {
                var (cat, opts) = pair;
                if (!cat.Requirements.Any()) return;
                spc.AddSource("SpecTrace.Requirements.g.cs", SourceText.From(EmitCatalog(cat, opts), Encoding.UTF8));
            });

            // Se lee por sintaxis y no por semántica: el argumento suele ser una constante del propio
            // catálogo generado (Requirements.ORD_001), que todavía no existe cuando corre este paso.
            var implemented = context.SyntaxProvider
                .CreateSyntaxProvider(
                    static (node, _) => node is AttributeSyntax attr && IsImplementsName(attr.Name),
                    static (ctx, _) => ReadReference(((AttributeSyntax)ctx.Node).ArgumentList))
                .Where(static r => r != null)
                .Select(static (r, _) => r!)
                .Collect();

            context.RegisterSourceOutput(implemented.Combine(catalog), (spc, pair) =>
            {
                var (refs, cat) = pair;
                var ids = refs
                    .Select(r => r.StartsWith(IdentPrefix, StringComparison.Ordinal)
                        ? cat.FindByIdentifier(r.Substring(IdentPrefix.Length))?.Id
                        : cat.TryGet(r, out var req) ? req.Id : null)
                    .Where(id => id != null)
                    .Select(id => id!)
                    .ToList();
                if (ids.Count == 0) return;
                spc.AddSource("SpecTrace.Implemented.g.cs", SourceText.From(EmitImplemented(ids), Encoding.UTF8));
            });
        }

        private const string IdentPrefix = "ident:";

        private static bool IsImplementsName(NameSyntax name)
        {
            var simple = name switch
            {
                QualifiedNameSyntax q => q.Right.Identifier.Text,
                AliasQualifiedNameSyntax a => a.Name.Identifier.Text,
                SimpleNameSyntax s => s.Identifier.Text,
                _ => string.Empty,
            };
            return simple == "Implements" || simple == "ImplementsAttribute";
        }

        /// <summary>Devuelve el ID literal ("ORD-001") o "ident:ORD_001" si se usó una constante del catálogo.</summary>
        private static string? ReadReference(AttributeArgumentListSyntax? args)
        {
            if (args == null || args.Arguments.Count == 0) return null;
            return args.Arguments[0].Expression switch
            {
                LiteralExpressionSyntax lit when lit.IsKind(SyntaxKind.StringLiteralExpression) => lit.Token.ValueText,
                MemberAccessExpressionSyntax member => IdentPrefix + member.Name.Identifier.Text,
                IdentifierNameSyntax ident => IdentPrefix + ident.Identifier.Text,
                _ => null,
            };
        }

        internal static string EmitCatalog(SpecCatalog catalog, SpecTraceOptions options)
        {
            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated>Generado por SpecTrace a partir de los ficheros *.spec.md. No editar.</auto-generated>");
            sb.AppendLine("#nullable enable");
            sb.AppendLine($"namespace {options.CatalogNamespace}");
            sb.AppendLine("{");
            sb.AppendLine("    /// <summary>IDs de los requisitos definidos en las specs.</summary>");
            sb.AppendLine($"    [global::System.CodeDom.Compiler.GeneratedCode(\"SpecTrace\", \"{Version}\")]");
            sb.AppendLine("    internal static partial class Requirements");
            sb.AppendLine("    {");

            foreach (var req in catalog.Requirements)
            {
                AppendDoc(sb, "        ", req);
                if (req.IsDeprecated)
                {
                    sb.AppendLine($"        [global::System.Obsolete(\"El requisito {req.Id} está deprecated en la spec.\")]");
                }

                sb.AppendLine($"        public const string {req.Identifier} = \"{req.Id}\";");
                sb.AppendLine();
            }

            sb.AppendLine("        /// <summary>Todos los requisitos que exigen implementación y test (approved / implemented).</summary>");
            sb.Append("        public static global::System.Collections.Generic.IReadOnlyList<string> Enforced { get; } = new string[] { ");
            sb.Append(string.Join(", ", catalog.Requirements.Where(r => r.IsEnforced).Select(r => "\"" + r.Id + "\"")));
            sb.AppendLine(" };");
            sb.AppendLine("    }");
            sb.AppendLine();
            sb.AppendLine("    /// <summary>IDs de los criterios de aceptación, agrupados por requisito.</summary>");
            sb.AppendLine($"    [global::System.CodeDom.Compiler.GeneratedCode(\"SpecTrace\", \"{Version}\")]");
            sb.AppendLine("    internal static partial class AcceptanceCriteria");
            sb.AppendLine("    {");

            foreach (var req in catalog.Requirements.Where(r => r.Criteria.Count > 0))
            {
                sb.AppendLine($"        /// <summary>Criterios de {Xml(req.Id)}: {Xml(req.Title)}</summary>");
                sb.AppendLine($"        public static class {req.Identifier}");
                sb.AppendLine("        {");
                foreach (var c in req.Criteria)
                {
                    sb.AppendLine($"            /// <summary>{Xml(c.Text)}</summary>");
                    sb.AppendLine($"            public const string {SpecNaming.ToIdentifier(c.Id)} = \"{c.Id}\";");
                }

                sb.AppendLine("        }");
            }

            sb.AppendLine("    }");
            sb.AppendLine("}");
            return sb.ToString();
        }

        internal static string EmitImplemented(IEnumerable<string> ids)
        {
            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated>Generado por SpecTrace. No editar.</auto-generated>");
            foreach (var id in ids.Distinct(StringComparer.OrdinalIgnoreCase).OrderBy(i => i, StringComparer.Ordinal))
            {
                sb.AppendLine($"[assembly: global::SpecTrace.SpecTraceImplemented(\"{id.Replace("\"", "")}\")]");
            }

            return sb.ToString();
        }

        private static void AppendDoc(StringBuilder sb, string indent, SpecRequirement req)
        {
            sb.AppendLine($"{indent}/// <summary>{Xml(req.Id)} · {Xml(req.Title)} ({req.Status})</summary>");
            if (req.Statement.Length > 0)
            {
                sb.AppendLine($"{indent}/// <remarks>{Xml(req.Statement)}</remarks>");
            }
        }

        private static string Xml(string text) => SecurityElement.Escape(text) ?? string.Empty;
    }
}
